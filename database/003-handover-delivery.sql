-- Additive handover ledger. Does not update offboarding operations or connector results.
BEGIN;

CREATE TABLE IF NOT EXISTS iam_handover_config (
 singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
 max_reservations integer NOT NULL CHECK (max_reservations > 0)
);
INSERT INTO iam_handover_config VALUES (true,20) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS iam_handover_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id bigint NOT NULL REFERENCES iam_operations(id),
 cycle bigint NOT NULL,
 target_email text NOT NULL,
 recipient text NOT NULL,
 owner text NOT NULL,
 status text NOT NULL CHECK (status IN ('reserved','sending','sent','failed_before_send','unknown')),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 authorized_at timestamptz,
 finished_at timestamptz,
 provider_message_id text,
 result_code text,
 review_note text,
 UNIQUE(operation_id,recipient)
);
CREATE INDEX IF NOT EXISTS iam_handover_created ON iam_handover_requests(created_at);

CREATE OR REPLACE FUNCTION iam_handover_eligible(p_operation bigint,p_email text)
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT jsonb_build_object('full_name',e.full_name,'email',e.email,
   'access_groups',e.access_groups,'status',e.status)
 FROM iam_operations o JOIN employees e ON e.email=o.target_email
 CROSS JOIN iam_runtime r
 WHERE o.id=p_operation AND o.kind='offboard' AND o.status='succeeded'
 AND o.target_email=p_email AND e.status='OFFBOARDED'
 AND r.singleton AND o.cycle=r.cycle AND r.owner IS NULL AND NOT r.reset_pending
 AND p_email IN ('john.carter@demo-corp.com','sarah.connor@demo-corp.com',
  'tchalla.udaku@demo-corp.com','ellen.ripley@demo-corp.com','arthur.dent@demo-corp.com',
  'marty.mcfly@demo-corp.com','dana.scully@demo-corp.com')
 AND (SELECT count(*) FROM iam_steps s WHERE s.operation_id=o.id)=3
 AND NOT EXISTS(SELECT 1 FROM iam_steps s WHERE s.operation_id=o.id AND s.status<>'succeeded')
 AND EXISTS(SELECT 1 FROM iam_steps s WHERE s.operation_id=o.id AND s.connector='postgres')
 AND EXISTS(SELECT 1 FROM iam_steps s WHERE s.operation_id=o.id AND s.connector='erp')
 AND EXISTS(SELECT 1 FROM iam_steps s WHERE s.operation_id=o.id AND s.connector='gcp');
$$;

CREATE OR REPLACE FUNCTION iam_handover_result(p_id bigint,p_repeated boolean DEFAULT false)
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT jsonb_build_object('request_id',id::text,'status',status,'repeated',p_repeated,
  'success',status='sent','code',CASE status
   WHEN 'reserved' THEN 'HANDOVER_PREPARING' WHEN 'sending' THEN 'HANDOVER_IN_PROGRESS'
   WHEN 'sent' THEN 'HANDOVER_ACCEPTED' WHEN 'unknown' THEN 'HANDOVER_UNKNOWN'
   ELSE 'HANDOVER_FAILED_BEFORE_SEND' END,
  'http_status',CASE WHEN status IN ('reserved','sending') THEN 202
   WHEN status='sent' THEN 200 ELSE 409 END)
 FROM iam_handover_requests WHERE id=p_id;
$$;

CREATE OR REPLACE FUNCTION iam_handover_reserve(p_operation bigint,p_email text,p_recipient text,p_owner text)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE cap integer; employee jsonb; existing iam_handover_requests%ROWTYPE; request_id bigint;
 recipient_normalized text := lower(trim(p_recipient));
BEGIN
 IF p_operation IS NULL OR p_operation<=0 OR coalesce(p_owner,'')='' OR length(p_owner)>128
  OR p_recipient IS NULL OR length(p_recipient)>254
  OR p_recipient ~ '[[:space:],;<>:"\\]' OR recipient_normalized !~ '^[^@]+@[^@]+\.[^@]+$' THEN
  RETURN jsonb_build_object('acquired',false,'code','INVALID_REQUEST','http_status',400);
 END IF;
 -- Serialize quota admission, including different recipients claiming the final slot.
 SELECT max_reservations INTO cap FROM iam_handover_config WHERE singleton FOR UPDATE;
 IF cap IS NULL THEN RAISE EXCEPTION 'Handover configuration unavailable'; END IF;
 SELECT * INTO existing FROM iam_handover_requests
  WHERE operation_id=p_operation AND recipient=recipient_normalized;
 IF FOUND THEN
  IF existing.target_email IS DISTINCT FROM p_email THEN
   RETURN jsonb_build_object('acquired',false,'code','HANDOVER_NOT_ELIGIBLE','http_status',409);
  END IF;
  RETURN iam_handover_result(existing.id,true)||jsonb_build_object('acquired',false);
 END IF;
 -- Short lock coordinates eligibility with the existing reset/offboarding claim.
 PERFORM 1 FROM iam_runtime WHERE singleton FOR UPDATE;
 employee:=iam_handover_eligible(p_operation,p_email);
 IF employee IS NULL THEN
  RETURN jsonb_build_object('acquired',false,'code','HANDOVER_NOT_ELIGIBLE','http_status',409);
 END IF;
 IF (SELECT count(*) FROM iam_handover_requests WHERE created_at>clock_timestamp()-interval '24 hours')>=cap THEN
  RETURN jsonb_build_object('acquired',false,'code','HANDOVER_LIMIT_REACHED','http_status',429);
 END IF;
 INSERT INTO iam_handover_requests(operation_id,cycle,target_email,recipient,owner,status)
 SELECT p_operation,cycle,p_email,recipient_normalized,p_owner,'reserved' FROM iam_operations WHERE id=p_operation
 RETURNING id INTO request_id;
 RETURN iam_handover_result(request_id)||jsonb_build_object('acquired',true,'employee',employee);
END;
$$;

CREATE OR REPLACE FUNCTION iam_handover_authorize(p_id bigint,p_owner text)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE h iam_handover_requests%ROWTYPE;
BEGIN
 PERFORM 1 FROM iam_runtime WHERE singleton FOR UPDATE;
 SELECT * INTO h FROM iam_handover_requests WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR h.owner IS DISTINCT FROM p_owner OR h.status<>'reserved' THEN
  RETURN jsonb_build_object('authorized',false,'code','HANDOVER_WRITE_BLOCKED','http_status',409);
 END IF;
 IF iam_handover_eligible(h.operation_id,h.target_email) IS NULL THEN
  UPDATE iam_handover_requests SET status='failed_before_send',finished_at=clock_timestamp(),
   result_code='ELIGIBILITY_CHANGED' WHERE id=h.id;
  RETURN iam_handover_result(h.id)||jsonb_build_object('authorized',false);
 END IF;
 UPDATE iam_handover_requests SET status='sending',authorized_at=clock_timestamp() WHERE id=h.id;
 RETURN jsonb_build_object('authorized',true,'request_id',h.id::text);
END;
$$;

CREATE OR REPLACE FUNCTION iam_handover_finish(p_id bigint,p_owner text,p_outcome text,p_message_id text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE h iam_handover_requests%ROWTYPE;
BEGIN
 SELECT * INTO h FROM iam_handover_requests WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR h.owner IS DISTINCT FROM p_owner THEN RAISE EXCEPTION 'Handover owner mismatch'; END IF;
 IF h.status NOT IN ('reserved','sending') THEN RETURN iam_handover_result(h.id,true); END IF;
 IF p_outcome NOT IN ('sent','unknown','failed_before_send') OR p_outcome IS NULL
  OR (p_outcome='sent' AND (h.status<>'sending' OR coalesce(p_message_id,'')='' OR length(p_message_id)>512))
  OR (p_outcome='failed_before_send' AND h.status<>'reserved') THEN
  RAISE EXCEPTION 'Invalid handover transition';
 END IF;
 UPDATE iam_handover_requests SET status=p_outcome,finished_at=clock_timestamp(),
  provider_message_id=CASE WHEN p_outcome='sent' THEN p_message_id ELSE NULL END,
  result_code=CASE p_outcome WHEN 'sent' THEN 'PROVIDER_ACCEPTED' WHEN 'unknown' THEN 'SEND_UNCONFIRMED' ELSE 'PRE_SEND_FAILED' END
 WHERE id=h.id;
 INSERT INTO audit_log(target_email,action,status,requester,detail)
 VALUES(h.target_email,'Handover Report',CASE p_outcome WHEN 'sent' THEN 'Success'
  WHEN 'unknown' THEN 'Needs Review' ELSE 'Failed Before Send' END,h.recipient,
  jsonb_build_object('handover_request_id',h.id::text,'operation_id',h.operation_id::text,
   'cycle',h.cycle,'execution_id',h.owner,'outcome',p_outcome,
   'gmail_message_id',CASE WHEN p_outcome='sent' THEN p_message_id ELSE NULL END));
 RETURN iam_handover_result(h.id);
END;
$$;

-- No resending/releasing function: stopped reserved/sending require documented review.
COMMIT;
